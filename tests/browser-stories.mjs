import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { startEditor, root } from './helpers/editor.mjs';

const editor = await startEditor(5217, 'browser-stories');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const checks = [];
try {
  const initial = await editor.request('author');
  mkdirSync(join(root, '.local/stories'), { recursive: true });
  for (const viewport of [{ width: 1440, height: 960 }, { width: 390, height: 844 }]) {
    const current = await editor.request('project');
    if (current.revision) await editor.request('restore', { revision: current.revision, document: JSON.stringify(initial) });
    const page = await browser.newPage({ viewport }); const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.route('**/editor-api/**', async route => { const response = await route.fetch({ url: editor.base + route.request().url().split('/editor-api/')[1], timeout: 180000 }); await route.fulfill({ response }); });
    await page.goto('http://127.0.0.1:5175', { waitUntil: 'networkidle' });
    await expect(page.getByLabel('当前剧本', { exact: true })).toBeEnabled({ timeout: 120000 });
    await page.getByRole('button', { name: '内容编辑', exact: true }).click();
    await page.getByRole('button', { name: '剧情', exact: true }).click();
    const panel = page.locator('.story-editor');
    await expect(panel).toHaveAttribute('aria-busy', 'false', { timeout: 120000 });
    await panel.locator('input[type=file]').first().setInputFiles(join(root, '.local/stories/export.ew4mod'));
    await expect(page.getByRole('button', { name: '应用到 R 版工程', exact: true })).toBeEnabled({ timeout: 120000 });
    assert.equal((await editor.request('author')).files['rewrite/story/catalog.json'], undefined);
    await page.getByRole('button', { name: '应用到 R 版工程', exact: true }).click();
    await expect(page.getByLabel('剧情场景', { exact: true })).toHaveValue('opening', { timeout: 120000 });
    checks.push(viewport.width + ': ZIP import preview and apply');
    const doc = await editor.request('stories');
    doc.catalog.backgrounds.map = 'client/ui/main.png';
    const commander = doc.images.find(p => p.endsWith('/Napoleon.png'));
    assert(commander);
    doc.catalog.characters.officer = { name: '拿破仑', poses: { standing: { image: commander, width: 256, height: 256 } } };
    doc.catalog.scenes.opening.steps[0].actors = [{ id: 'a', character: 'officer', slot: 'left', scale: .35 }];
    doc.catalog.scenes.opening.steps[0].speaker = 'a';
    await page.getByTitle('编辑完整剧情 JSON', { exact: true }).click();
    await page.getByLabel('完整剧情 JSON', { exact: true }).fill(JSON.stringify(doc.catalog));
    await page.getByRole('button', { name: '载入 JSON', exact: true }).click();
    await page.getByLabel('剧情台词', { exact: true }).fill('新的剧情草稿，选择右路继续。');
    const beforePlay = await editor.request('author');
    await page.getByRole('button', { name: '播放预览', exact: true }).click();
    const player = page.frameLocator('iframe[title="剧情播放器"]');
    await expect(player.locator('.story-text')).toHaveText('新的剧情草稿，选择右路继续。', { timeout: 20000 });
    await expect(player.locator('.story-background')).toBeVisible();
    assert.equal(await player.locator('.story-background').evaluate(img => img.naturalWidth > 0), true);
    assert.equal(await player.locator('.story-actor img').first().evaluate(img => img.naturalWidth > 0), true);
    await page.screenshot({ path: join(root, `.local/stories/player-${viewport.width}.png`) });
    await player.getByRole('button', { name: '右路', exact: true }).click();
    await expect(player.locator('.story-text')).toHaveText('右路抵达。');
    await page.getByTitle('关闭剧情预览', { exact: true }).click();
    assert.deepEqual(await editor.request('author'), beforePlay);
    checks.push(viewport.width + ': real player media and branch, author unchanged');
    await page.getByRole('button', { name: '原版', exact: true }).click();
    await expect(page.getByRole('button', { name: '原版', exact: true })).toHaveAttribute('aria-pressed', 'true');
    const mapClose = page.locator('.dialog-head .close');
    if (await mapClose.isVisible()) await mapClose.click();
    await page.getByRole('button', { name: 'R 版', exact: true }).click();
    await expect(page.getByLabel('剧情台词', { exact: true })).toHaveValue('新的剧情草稿，选择右路继续。');
    checks.push(viewport.width + ': version switches retain independent draft');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.getByRole('heading', { name: '共享素材', exact: true }).scrollIntoViewIfNeeded();
    await expect(page.getByRole('heading', { name: '共享素材', exact: true })).toBeInViewport();
    await panel.evaluate(el => { el.scrollTop = 0; });
    assert.deepEqual(errors, []);
    await page.screenshot({ path: join(root, `.local/stories/editor-${viewport.width}.png`) });
    await page.close();
  }
  writeFileSync(join(root, '.local/stories/browser-result.json'), JSON.stringify({ checks }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks }));
} finally { await browser.close(); await editor.stop(); }
